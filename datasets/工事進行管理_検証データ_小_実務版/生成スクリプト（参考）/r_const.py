def bphoto(work, state, date, seed):
    """工事黒板の入った現場写真（合成）。K-2504 の写真台帳用"""
    rng = np.random.default_rng(seed)
    W, H = 880, 608
    im = photo_bg(W, H, rng, (128 + int(rng.integers(-10, 10)), 128, 124))
    d = ImageDraw.Draw(im)
    d.rectangle((0, 450, W, H), fill=(92, 92, 88))
    o = int(rng.integers(-20, 20))
    for y in (96 + o, 136 + o):
        d.line((0, y, W, y - 24), fill=(190, 190, 185), width=8)
    for x in range(24, W, 44):
        d.line((x, 96 + o - x * 24 // W, x + 5, 136 + o - x * 24 // W), fill=(175, 175, 170), width=4)
    d.line((0, 184 + o, 336, 172 + o), fill=(40, 40, 40), width=11)
    bx, by, bw, bh = 88 + int(rng.integers(-30, 200)), 240, 480, 320
    d.rectangle((bx, by, bx + bw, by + bh), fill=(26, 60, 46), outline=(228, 226, 214), width=7)
    hf, lf = ImageFont.truetype(fp('H'), 30), ImageFont.truetype(fp('G'), 19)
    for i, (lab, val) in enumerate([('工事名', dm.PJ['K-2504']['name'][:14]), ('工　種', work), ('撮影日', date), ('状　況', state)]):
        y = by + 16 + i * 74
        d.line((bx + 8, y + 69, bx + bw - 8, y + 69), fill=(200, 205, 195), width=2)
        d.line((bx + 104, y, bx + 104, y + 69), fill=(200, 205, 195), width=2)
        d.text((bx + 19, y + 22), lab, font=lf, fill=(225, 228, 218))
        d.text((bx + 117, y + 13), val, font=hf if len(val) <= 11 else ImageFont.truetype(fp('H'), 24), fill=(240, 242, 232))
    return im


def album(path, shots, first_no, first_page, total):
    """写真台帳: 1ページに2枚。写真は JPEG のまま埋め込む"""
    doc = fitz.open()
    for n in range(0, len(shots), 2):
        pg = doc.new_page(width=595, height=842)
        tx = lambda x, y, s, sz=9, k='G': pg.insert_text((x, y), s, fontsize=sz, fontname='f' + k, fontfile=fp(k))
        tx(40, 40, '工事写真台帳　K-2504　北関東ロジ 物流センター 自動倉庫増設工事　（2026年3月）', 10.5, 'B')
        tx(500, 40, f'{first_page + n // 2} / {total} ページ', 8.5)
        for j, (d_, work, state) in enumerate(shots[n:n + 2]):
            no = first_no + n + j
            buf = io.BytesIO()
            bphoto(work, state, f'2026. 3. {d_.day}', 3000 + no).save(buf, 'JPEG', quality=72)
            y0 = 56 + j * 384
            pg.insert_image(fitz.Rect(60, y0, 535, y0 + 328), stream=buf.getvalue())
            tx(60, y0 + 344, f'写真 No.{no:03d}　撮影日 {sd(d_)}　工種 {work}　撮影者 関')
            tx(60, y0 + 358, f'状況：{state}')
    doc.save(path, deflate=True, garbage=4)
    return V(path)


