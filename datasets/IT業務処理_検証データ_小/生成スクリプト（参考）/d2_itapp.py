def recalc(c):
    KV, DT, calc, chk = c.KV, c.DT, c.calc, c.chk
    # S01: 設計書の仕様で全行を再計算
    rows, heads = c.xl('請求明細データ_サンプル3か月.xlsx'), c.xl('請求明細データ_サンプル3か月.xlsx', 1)
    kd = KV['請求計算_機能設計書']
    chk(kd['k_r1'] == '3％' and kd['k_ra1'].startswith('4％') and kd['k_r2'] == '5％' and kd['k_ra2'].startswith('6％') and '切り捨て' in kd['k_round'], '設計書の印字')
    bad, sub, rankA, edge = {}, {}, 0, 0
    for no, d, cu, rank, li, pc, pn, q, price, r, amt in rows:
        d = day(d)
        rr = (5 if q >= 500 else (3 if q >= 100 else 0)) + (1 if rank == 'A' and q >= 100 else 0)
        exp = q * price * (100 - rr) // 100
        chk(r == rr, f'値引率 {no}-{li}')
        if amt != exp:
            bad.setdefault((d.year, d.month), []).append((no, li, amt - exp))
        sub[no] = sub.get(no, 0) + amt
        rankA += rank == 'A' and rr in (4, 6)
        edge += q in (100, 500)
    for no, d, cu, rank, s, tax, tot in heads:
        chk(s == sub[no] and tax == s * 10 // 100 and tot == s + tax, f'請求書合計 {no}')
    for y, m in MONTHS:
        calc[('S01', f'{y}年{m}月')] = A if bad.get((y, m)) else N
    chk(all(day([r for r in rows if r[0] == b[0]][0][1]) >= BUG0 and b[2] == 1 for b in bad.get((2025, 11), [])), '誤りは11/11以降・1円')
    for ym, no in DT['PICK'].items():
        k = KV[f'01_請求書控_{no}']
        x = [h for h in heads if h[0] == no][0]
        chk(num(k['k_sub']) == x[4] and num(k['k_tax']) == x[5] and num(k['k_total']) == x[6], f'請求書控 {no}')
    c.traps += [f'S01: ランクAの加算が適用された行 {rankA} 行、数量がちょうど100・500個の行 {edge} 行', f'S01 11月: 誤りは {len(bad.get((2025, 11), []))} 行（各1円）']
    # S02: ログを日ごとに比べる
    errs = {r[0]: r for r in c.xl('連携エラー一覧_2025年度.xlsx')}
    for y, m in MONTHS:
        tag = f'{y}-{m:02d}'
        rel = f'{FO["F2"]}/02_連携実行ログ_{tag}'
        L = c.text(rel + '.log').splitlines() if os.path.exists(f'{c.OUT}/B_対照版/{rel}.log') else ''.join(p.get_text() for p in fitz.open(f'{c.OUT}/B_対照版/{rel}.pdf')).splitlines()
        send, recv, redo = {}, {}, set()
        for l in L:
            mm = re.match(r'(\d{4}-\d\d-\d\d) \S+ IF_SALES_ACC (送信|受信|再処理) 件数=(\d+) 金額=([\d,]+)', l)
            if mm:
                if mm.group(2) == '再処理':
                    redo.add(mm.group(1))
                else:
                    (send if mm.group(2) == '送信' else recv)[mm.group(1)] = (int(mm.group(3)), num(mm.group(4)))
        sheet_ = {f'{r["d"]:%Y-%m-%d}': r for r in DT['IF'][(y, m)]}
        chk(set(send) == set(recv) == set(sheet_), f'ログと照合表の日 {tag}')
        ok, nm = True, 0
        for d_ in send:
            r = sheet_[d_]
            chk((r['sc'], r['sa'], r['rc'], r['ra']) == send[d_] + recv[d_], f'照合表の転記 {d_}')
            if send[d_] != recv[d_]:
                nm += 1
                es = re.findall(r'E-\d\d-\d{3}', r['memo'].replace('・', ' E-' + r['memo'][r['memo'].find('E-') + 2:r['memo'].find('E-') + 5] if '・' in r['memo'] else ''))
                good = r['judge'] == '×' and es and all(e in errs and errs[e][5] == '再処理済' for e in es) and add_bd(D(*map(int, d_.split('-'))), 1).strftime('%Y-%m-%d') in redo
                ok = ok and bool(good)
            else:
                ok = ok and r['judge'] == '○'
        ok = ok and '溝口' in KV[f'02_連携照合表_{tag}']['k_st_ok']
        calc[('S02', f'{y}年{m}月')] = N if ok else A
        c.traps.append(f'S02 {tag}: 不一致の日 {nm} 日')
    # S03: 5営業日・承認
    for eno in ESMP:
        e = errs[eno]
        k = KV[f'03_エラー対応票_{eno}']
        ok = bd_count(day(e[1]), day(e[6])) <= 5 and e[5] in ('再処理済', '取消') and '溝口' in k['k_st_ok'] and k['k_done'] == jd(day(e[6])) and num(k['k_amt']) == e[4]
        if e[5] == '取消':
            ok = ok and '取消' in k['k_action']
            c.traps.append(f'S03 {eno}: 取消（理由の記載あり）')
        if (day(e[6]) - day(e[1])).days > 7:
            c.traps.append(f'S03 {eno}: {(day(e[6]) - day(e[1])).days}日後だが {bd_count(day(e[1]), day(e[6]))} 営業日目')
        calc[('S03', eno)] = N if ok else A
    chk(all(r[5] in ('再処理済', '取消') for r in errs.values()), '未処理のエラー')
    # S04: リリース記録 → 変更管理票
    kr = KV['04_本番リリース記録']
    for i, cr in enumerate(DT['CRS']):
        no, kind, ad, mod, ver, what, dev, rel, (rd, rt), td, tres, a1, bname, a2 = cr
        k = KV[f'04_変更管理票_{no}']
        chk(kr[f'k_rel{i}_cr'] == no and kr[f'k_rel{i}_by'] == UID[rel] and k['k_dev'] == dev and k['k_relby'] == rel, f'リリース記録と票 {no}')
        appr_ok = max(a1, a2) <= rd if kind == '通常' else bd_count(rd, max(a1, a2)) <= 3
        ok = appr_ok and k['k_dev'] != k['k_relby'] and '省略' not in k['k_tres'] and '永井' in k['k_st_ka'] and bname in k['k_st_bu']
        calc[('S04', no)] = N if ok else A
        if kind == '緊急':
            c.traps.append(f'S04 {no}: 緊急変更。承認はリリースの {bd_count(rd, max(a1, a2))} 営業日後')
    # S05: 設定とテスト
    ks, k1, k2 = KV['05_与信チェック設定画面'], KV['05_与信チェック_テスト結果_1'], KV['05_与信チェック_テスト結果_2']
    s1, s2 = num(k1['k_ar']) + num(k1['k_bl']) + num(k1['k_cur']), num(k2['k_ar']) + num(k2['k_bl']) + num(k2['k_cur'])
    ok = '登録不可' in ks['k_act'] and '＞' in ks['k_expr'] and 'ありません' in ks['k_hist'] and s1 == num(k1['k_limit']) and '登録済' in k1['k_state'] and s2 > num(k2['k_limit']) and 'E-3101' in k2['k_res']
    calc[('S05', '設定・テスト')] = N if ok else A
    c.traps.append(f'S05: 合計 {s1:,}（限度額と同額）は登録可、{s2:,} はエラー')
