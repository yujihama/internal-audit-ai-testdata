def rate_of(q, rank):
    return (5 if q >= 500 else (3 if q >= 100 else 0)) + (1 if rank == 'A' and q >= 100 else 0)


def gen_invoices(rng):
    cust = [(f'C{n:03d}', 'A' if n % 4 == 1 else 'B') for n in range(1, 31)]
    inv = []
    for y, m in MONTHS:
        bds = [d for d in drange(D(y, m, 1), D(y + (m == 12), m % 12 + 1, 1) - dt.timedelta(days=1)) if is_bd(d)]
        ds = sorted(rng.choice(bds) for _ in range(40))
        for n, d in enumerate(ds, 1):
            code, rank = rng.choice(cust)
            lines = []
            for li in range(rng.randint(2, 4)):
                p = rng.randrange(len(PROD))
                price = int(PROD[p][3] * rng.choice([0.93, 0.957, 0.971, 1.0, 1.013]))
                q = rng.choice(QTY)
                r = rate_of(q, rank)
                raw = q * price * (100 - r)
                amt = (raw + 50) // 100 if (BUG0 <= d <= BUG1 and r > 0) else raw // 100   # 誤りの期間は四捨五入
                lines.append(dict(p=p, q=q, price=price, r=r, amt=amt, ok=raw // 100))
            sub = sum(l['amt'] for l in lines)
            inv.append(dict(no=f'INV-{y % 100}{m:02d}-{n:03d}', d=d, c=code, rank=rank, lines=lines, sub=sub, tax=sub // 10, total=sub + sub // 10))
    return inv


def gen_if(rng):
    """日次連携の実績。戻り値: {(y,m): [dict(d, sc, sa, rc, ra, err, judge, memo, redo)]}"""
    ev = {D(2025, 7, 14): dict(err=1, lost=128_700, memo='エラー1件 E-07-003。7/15 再処理済'), D(2026, 2, 12): dict(err=2, lost=96_800 + 214_500, memo='エラー2件 E-02-001・002。2/13 再処理済'),
          D(2025, 11, 18): dict(err=0, lost=45_000, miss=True)}
    out = {}
    for y, m in MONTHS:
        rows = []
        for d in [d for d in drange(D(y, m, 1), D(y + (m == 12), m % 12 + 1, 1) - dt.timedelta(days=1)) if is_bd(d)]:
            sc, sa = rng.randint(118, 176), rng.randint(140, 260) * 100_000 + rng.randint(0, 999) * 100
            e = ev.get(d, {})
            rc, ra = sc - e.get('err', 0), sa - e.get('lost', 0)
            mism = (sc, sa) != (rc, ra)
            rows.append(dict(d=d, sc=sc, sa=sa, rc=rc, ra=ra, err=e.get('err', 0), judge='○' if (not mism or e.get('miss')) else '×', memo=e.get('memo', ''),
                             who=['立花', '宮下'][d.isocalendar()[1] % 2], redo=(e['err'], e['lost']) if e.get('err') else None))
        out[(y, m)] = rows
    return out


def if_log(rows):
    L = []
    prev = None
    for r in rows:
        if prev and prev['redo']:
            L.append(f'{r["d"]:%Y-%m-%d} 09:2{r["d"].day % 10}:33 IF_SALES_ACC 再処理 件数={prev["redo"][0]} 金額={prev["redo"][1]:,} エラー=0')
        L.append(f'{r["d"]:%Y-%m-%d} 22:00:0{r["d"].day % 7 + 1} IF_SALES_ACC 送信 件数={r["sc"]} 金額={r["sa"]:,}')
        L.append(f'{r["d"]:%Y-%m-%d} 22:0{r["d"].day % 4 + 2}:1{r["d"].day % 9} IF_SALES_ACC 受信 件数={r["rc"]} 金額={r["ra"]:,} エラー={r["err"]}')
        prev = r
    return L


