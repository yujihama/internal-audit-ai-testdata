def contract(k):
    return PJ[k]['contract0'] + PJ[k]['add']


def bud(k, now=True):
    return sum(w[2 if now else 1] for w in PJ[k]['wk']) + PJ[k]['exp']


def pct(k, used=None):
    return round(PJ[k]['cost'] / bud(k, (used or PJ[k]['used']) == 'now') * 100, 1)


def rev(k, used=None):
    return int(round(contract(k) * pct(k, used) / 100))


def gen_costs(rng):
    rows = []
    for k, p in PJ.items():
        ms = []
        d = p['t0'].replace(day=1)
        while d <= END:
            ms.append((d.year, d.month))
            d = (d.replace(day=28) + dt.timedelta(days=5)).replace(day=1)
        part = []
        for i, (nm, b0, b1, (a, b), gp, rp) in enumerate(p['wk']):
            if gp == 0:
                continue
            for (y, m) in ms:
                pos = (y - M0[0]) * 12 + m - M0[1]
                if a - 1 <= pos <= b:
                    for kind, vendor in (('外注', f'{nm}の協力会社'), ('材料', '資材の仕入先')):
                        if rng.random() < 0.75:
                            part.append([k, f'{y}/{m:02d}', nm, kind, vendor, rng.randint(3, 60) * 50_000])
        for (y, m) in ms:
            part.append([k, f'{y}/{m:02d}', '現場経費', '経費', '現場の諸経費', rng.randint(4, 12) * 20_000])
            part.append([k, f'{y}/{m:02d}', '現場経費', '労務', '現場代理人の人件費', 620_000])
        f = p['cost'] / sum(r[5] for r in part)
        for r in part:
            r[5] = int(r[5] * f / 1000) * 1000
        part[-1][5] += p['cost'] - sum(r[5] for r in part)
        assert part[-1][5] > 0 and sum(r[5] for r in part) == p['cost']
        rows += part
    return rows


