def bom_all(path):
    """部品表の全製品の一覧（システムからの出力）。サンプルの3品番は元の部品表と同じ内容"""
    rng = random.Random(5)
    mats = [(f'{a}-{rng.randrange(100, 999)}', n, u, iu, cv) for a, n, u, iu, cv in
            [('A5052', 'アルミ角材 A5052', 'kg', 'kg', 1), ('A6061', 'アルミ丸棒 A6061', 'kg', 'kg', 1), ('S45C', 'S45C 丸棒', 'kg', 'kg', 1), ('SS400', 'SS400 平鋼', 'kg', 'kg', 1), ('SUS304', 'SUS304 丸棒', 'kg', 'kg', 1),
             ('BT-M4', '六角穴付ボルト M4', '本', '本', 1), ('BT-M6', '六角穴付ボルト M6', '本', '本', 1), ('BT-M8', '六角穴付ボルト M8', '本', '本', 1), ('NT-M6', '六角ナット M6', '個', '個', 1), ('WS-M6', '平座金 M6', '枚', '枚', 1),
             ('SS-M5', '止めねじ M5', '本', '本', 1), ('PN-4', '平行ピン φ4', '本', '本', 1), ('OR-P', 'Oリング', '個', '個', 1), ('SL', 'オイルシール', '枚', '枚', 1), ('BR-62', '深溝玉軸受', '個', '個', 1),
             ('GR-LI', 'グリス（リチウム系）', 'g', 'kg', 1000), ('RO', '防錆油', 'mL', 'L', 1000), ('LB', '製品ラベル', '枚', '枚', 1), ('PK', '梱包箱', '個', '個', 1), ('HS', '鋳物ハウジング', '個', '個', 1)] for _ in range(4)]
    names = ['シャフトホルダ', 'ベアリングユニット', 'カップリング', 'フランジ', 'ブラケット', 'スペーサ', 'カラー', 'プーリ', 'ギヤケース', 'ハウジング', 'ベースプレート', 'ガイドブロック', 'ストッパ', 'ジョイント', 'クランプ']
    prods = {}
    while len(prods) < 430:
        code = f'{rng.choice("ABCDEFGHJKLMNPRSTW")}{rng.choice("ABCEFGHKLMNPRSTXZ")}-{rng.randrange(10, 99) * 10}'
        if code in dm.BOM or code in prods:
            continue
        ms = rng.sample(mats, rng.randint(2, 5))
        prods[code] = (rng.choice(names), [(c, n, (round(rng.uniform(0.1, 2.5), 2) if u == 'kg' else rng.choice([4, 5, 6, 8, 10, 12]) if u in ('g', 'mL') else rng.randint(1, 6)), u, iu, cv) for c, n, u, iu, cv in ms])
    for near, base, k in (('AX-200L', 'AX-200', 1.6), ('AX-210', 'AX-200', 1.15), ('BR-310S', 'BR-310', 0.5), ('CP-450W', 'CP-450', 1.4)):      # よく似た品番（使用量が違う）
        prods[near] = (dm.BOM[base][0] + {'L': '（ロング）', 'S': '（小形）', 'W': '（幅広）', '0': '（改）'}[near[-1]],
                       [(c, n, (round(per * k, 2) if bu in ('kg',) else per if bu in ('本', '個', '枚') else int(per * k)), bu, iu, cv) for c, n, per, bu, iu, cv in dm.BOM[base][1]])
    prods.update(dm.BOM)
    rows = [[code, nm if i == 0 else '', c, n, f'{per:g}', bu, iu, '有効'] for code, (nm, ms) in sorted(prods.items()) for i, (c, n, per, bu, iu, cv) in enumerate(ms)]
    g = table_print(path, 'B0110 部品表マスタ一覧（全製品）　出力日時 2026/04/08 10:12　出力者 松井',
                    [('品番', 26, 'l'), ('品名', 46, 'l'), ('材料コード', 30, 'l'), ('材料名', 62, 'l'), ('1個あたり標準使用量', 34, 'r'), ('単位', 16, 'c'), ('出庫の単位', 22, 'c'), ('状態', 16, 'c')], rows,
                    foot=f'合計 {len(prods)} 品番　{len(rows):,} 行　　※ 標準使用量には、通常の加工で生じる切りくず・端材を含む。')
    INFO['bom_pages'] = g.pno + 1
    INFO['bom_at'] = {it: [r[0] for r in rows].index(it) // 45 + 1 for it in dm.BOM}
    return g


