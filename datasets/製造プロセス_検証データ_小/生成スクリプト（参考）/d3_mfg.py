def fmtq(v):
    return yen(int(v)) if float(v).is_integer() else f'{v:g}'


def std_use(m):
    """標準使用量（出庫の単位に換算）"""
    return [(c, n, round(per * m['qty'] / conv, 4), iu) for c, n, per, bu, iu, conv in BOM[m['item']][1]]


def measures(m, rng):
    out = []
    for i, (nm, disp, lo, hi, dg_) in enumerate(SPEC[m['item']]):
        v = INSP_OVR.get((m['s'], i)) or [round(lo + (hi - lo) * rng.uniform(0.25, 0.75), dg_) for _ in range(5)]
        out.append(v)
    return out


