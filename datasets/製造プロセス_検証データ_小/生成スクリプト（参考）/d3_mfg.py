def check_sheet(path, mc, name, y, m, seed):
    g = Pg(path, land=True, seed=seed)
    days = [d for d in drange(D(y, m, 1), D(y + (m == 12), m % 12 + 1, 1) - dt.timedelta(days=1))]
    work = [d for d in days if is_bd(d) and not (D(2025, 12, 27) <= d <= D(2026, 1, 4))]
    g.t(12, 12, '様式 製-041', 7.5)
    g.t(130, 21, f'設備 日常点検表（{y}年{m}月）', 15, 'B', al='c')
    g.t(12, 31, f'設備：{mc}　{name}', 11, 'B', key='k_mc')
    g.t(12, 37.5, '凡例：レ 良　× 異常（修理依頼書を起票する）　空欄 休業日　　点検は始業前に行う', 9)
    me = add_bd(days[-1], 2)
    g.appr(263, 8, [('月次確認', DS(g, '岩田', me), 'k_st_ok', dsd('岩田', me))], w=22, h=20)
    x0, y0, w1, cw, rh = 12, 44, 46, 7.3, 9.5
    g.rc(x0, y0, w1, 11, fill=GR)
    g.t(x0 + w1 / 2, y0 + 7, '点検項目', 9, al='c')
    marks = {}
    for i, d in enumerate(days):
        cx = x0 + w1 + i * cw
        g.rc(cx, y0, cw, 11, fill=GR)
        g.t(cx + cw / 2, y0 + 4.5, d.day, 8, al='c')
        g.t(cx + cw / 2, y0 + 9.3, '月火水木金土日'[d.weekday()], 7, al='c', col=(0.7, 0, 0) if not is_bd(d) else (0, 0, 0))
    labels = ITEMS + ['点検者', '班長確認']
    for r, lab in enumerate(labels):
        yy = y0 + 11 + r * rh
        g.rc(x0, yy, w1, rh, fill=GR)
        g.t(x0 + 2, yy + 6.2, lab, 9.5)
        for i, d in enumerate(days):
            cx = x0 + w1 + i * cw
            g.rc(cx, yy, cw, rh)
            if d not in work:
                continue
            if r < len(ITEMS):
                mk = '×' if (d, r) == XDAY and mc == 'L-03' else 'レ'
                marks[(d, r)] = mk
                g.hw(cx + 1.6, yy + 6.6, mk, 12, 'H', key='k_x' if mk == '×' else None)
            elif lab == '点検者':
                g.hw(cx + 1.4, yy + 6.6, '竹菅森'[(d.isocalendar()[1] + (mc == 'M-02')) % 3], 11, 'Z')
            else:
                wk = [w for w in work if w.isocalendar()[1] == d.isocalendar()[1]]
                if d == wk[-1]:
                    stampcell(g, '小野寺', cx + 0.4, yy + 1.4, 6.5)
                    marks[(d, 'wk')] = True
    g.box('k_first', x0 + w1, y0 + 11, cw * 7, rh, '第1週の点検（油圧）')
    g.t(12, y0 + 11 + len(labels) * rh + 6, '※ 異常（×）があった設備は、修理が完了し再点検で良となるまで使用しない（製造管理規程 第16条）。', 8.5)
    g.save()
    return g, marks, work


