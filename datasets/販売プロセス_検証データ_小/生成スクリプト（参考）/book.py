def sheet(wb, title, head, rows, widths, wrap=(), fmts=None, first=False, freeze='A2', border=True):
    ws = wb.active if first else wb.create_sheet()
    ws.title = title
    ws.append(head)
    for r in rows:
        ws.append(r)
    for ci, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(ci)].width = w
    for c in ws[1]:
        c.font = Font(name=FN, size=10, bold=True)
        c.fill = HF
        c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        c.border = BD
    if len(rows) < 3000:
        for row in ws.iter_rows(min_row=2):
            for c in row:
                c.font = Font(name=FN, size=10)
                c.alignment = Alignment(vertical='top', wrap_text=(c.column in wrap))
                if border:
                    c.border = BD
                if fmts and c.column in fmts:
                    c.number_format = fmts[c.column]
    ws.freeze_panes = freeze
    ws.auto_filter.ref = ws.dimensions
    return ws


