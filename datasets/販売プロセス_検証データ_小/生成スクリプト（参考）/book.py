def roll(vals):
    return A if A in vals else (U if U in vals else N)


def files_for(pid, sid, set_):
    ck = dict((p[0], p[1]) for p in PROC)[pid]
    if ck in ('C6', 'C7'):
        y, m = sid.split('年')
        pre = f'{ck}_{int(y)}-{int(m.split("月")[0]):02d}_'
    elif sid == '確認表':
        pre = 'C8_期末'
    else:
        pre = f'{ck}_{sid}_'
    fs = [m['path'] for m in MAN if m['set'] == set_ and os.path.basename(m['path']).startswith(pre) and pid in m['procs']]
    if pid == 'P12':
        fs += [m['path'] for m in MAN if m['set'] == set_ and '確認表' in m['path']]
    return fs


