def qty(n):
    z, it, b, per, loose = TAGS[n]
    return b * per + loose


def team(n):
    return ('矢野', '北村') if (n <= 8 or n >= 17) else ('相馬', '長尾')


def counted():
    t = {}
    for n in TAGS:
        t[TAGS[n][1]] = t.get(TAGS[n][1], 0) + SUM_ERR.get(n, qty(n))
    return t


def diffs():
    out = []
    cn = counted()
    for it, bk in BOOK.items():
        d = cn[it] - bk
        rate, amt = d / bk * 100, d * COST[it]
        out.append(dict(it=it, book=bk, cnt=cn[it], d=d, rate=rate, amt=amt, need=abs(rate) > 2 or abs(amt) > 100_000))
    return out


