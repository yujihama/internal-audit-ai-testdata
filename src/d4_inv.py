def recalc(c):
    KV, DT, calc, chk = c.KV, c.DT, c.calc, c.chk
    TG, SPC = DT['TAGS'], DT['SPECIAL']
    kt = {}
    for i in range(6):
        kt.update(KV[f'01_棚卸原票_{i * 4 + 1:03d}-{i * 4 + 4:03d}'])
    q = lambda n: TG[n][2] * TG[n][3] + TG[n][4]
    # T01: 連番
    nos = sorted(int(v.replace('No.', '')) for k, v in kt.items() if k.startswith('k_no'))
    kc = KV['01_原票管理表']
    calc[('T01', '連番（No.001〜024）')] = N if (nos == list(range(1, 25)) and '回収 24 枚' in kc['k_total'] and len(TG) + 1 == 21) else A
    calc[('T01', 'No.009（書損じ）')] = N if (kt['k_sp9'] == '書損じ' and kc['k_s9'] == '書損じ') else A
    calc[('T01', 'No.023・024（未使用）')] = N if (kt['k_sp23'] == kt['k_sp24'] == '未使用' and kc['k_s23'] == kc['k_s24'] == '未使用') else A
    c.traps += ['T01: 書損じ1枚・未使用2枚（いずれも回収）']
    # T02: 配置図の区画 → 完了確認表・原票
    kl, kdn = KV['倉庫配置図'], KV['02_区画別完了確認表']
    drawn = [z for z, tgt in DT['ZONES'] if tgt]
    chk(all(kl[f'k_{z.replace("-", "")}'] == z for z in drawn) and kl['k_検品場'] == '検品場', '配置図の区画名')
    listed = [kdn[f'k_z{i}'] for i in range(len(DT['DONE']))]
    tagz = {TG[n][0] for n in TG} | {v[1] for n, v in SPC.items() if v[0] == '在庫なし'}
    res = {z: N if (z in listed and z in tagz) else A for z in drawn}
    calc[('T02', 'C-4（仮置場）')], calc[('T02', 'C-3（在庫なし）')] = res['C-4'], res['C-3']
    calc[('T02', '検品場・出荷場')] = N if not any(z in listed for z, tgt in DT['ZONES'] if not tgt) else A
    calc[('T02', 'その他の区画')] = roll([res[z] for z in drawn if z not in ('C-3', 'C-4')])
    c.traps += ['T02 C-3: 在庫なしの原票あり', 'T02: 検品場・出荷場は棚卸対象外']
    # T03: 原票 → 集計表
    ks = KV['03_棚卸集計表']
    for n in T3S:
        tq = num(kt[f'k_q{n}'].split('（')[0])
        chk(tq == q(n), f'原票の数量 {n}')
        if TG[n][2]:
            chk(kt[f'k_b{n}'].startswith(f'{TG[n][2]}箱×{TG[n][3]}'), f'内訳 {n}')
            c.traps.append(f'T03 No.{n:03d}: 内訳 {kt[f"k_b{n}"]} ＝ {tq:,}')
        if '訂正' in kt[f'k_q{n}']:
            c.traps.append(f'T03 No.{n:03d}: 訂正印のある訂正（訂正後 {tq}）')
        calc[('T03', f'No.{n:03d}')] = N if num(ks[f'k_s{n}']) == tq else A
    chk('北村' in ks['k_st_chk'], '照合印')
    # T04: 差異の再計算
    book = {r[0]: (r[3], r[4]) for r in c.xl('帳簿在庫一覧_2026-03-31.xlsx')}
    cnt = {}
    for n in TG:
        cnt[TG[n][1]] = cnt.get(TG[n][1], 0) + num(ks[f'k_s{n}'])
    kd = KV['04_棚卸差異分析表']
    res, other = {}, []
    for i, (it, (bk, cost)) in enumerate(book.items()):
        d = cnt[it] - bk
        need = abs(d / bk * 100) > 2 or abs(d * cost) > 100_000
        if d:
            chk(num(kd[f'k_d{i}']) == d and num(kd[f'k_a{i}']) == d * cost and (kd[f'k_need{i}'] == '要') == need, f'差異分析表の印字 {it}')
        ok = True
        if need:
            kr = [x for x in c.stems if x.startswith('04_差異調査報告書') and KV[x]['k_item'].startswith(it)]
            ok = len(kr) == 1 and '梅田' in KV[kr[0]]['k_st_ka'] and '溝口' in KV[kr[0]]['k_st_kr'] and num(KV[kr[0]]['k_amt']) == d * cost
            c.traps.append(f'T04 {it}: 差異率 {d / bk * 100:+.2f}％、金額 {d * cost:+,}円 → 調査の対象')
        elif d and (abs(d / bk * 100) > 1.5 or abs(d * cost) > 80_000):
            c.traps.append(f'T04 {it}: 差異率 {d / bk * 100:+.2f}％、金額 {d * cost:+,}円 → 基準内')
        res[it] = N if ok else A
    for it in ('GM-60W-30', 'OR-P20-100', 'AC-20-50'):
        calc[('T04', it)] = res[it]
    calc[('T04', 'その他の品番')] = roll([v for k, v in res.items() if k not in ('GM-60W-30', 'OR-P20-100', 'AC-20-50')])
    chk('梅田' in kd['k_st_ka'] and '溝口' in kd['k_st_kr'], '差異分析表の承認')
    # T05: 立会・写真
    kw = KV['05_棚卸立会記録']
    for n in T5S:
        ok = num(kw[f'k_w{n}']) == q(n) == num(kw[f'k_t{n}']) and kw[f'k_r{n}'] == '一致'
        kp = KV.get(f'05_現物写真_No{n:03d}')
        if kp:
            per = num(kp['k_per'])
            bx, ls = re.findall(r'(\d+)箱 ＋(\d+)', kp['k_memo'])[0]
            ok = ok and int(bx) * per + int(ls) == q(n) and kp['k_code'] == TG[n][1]
            c.traps.append(f'T05 No.{n:03d}: 写真から {bx}箱×{per}＋{ls} ＝ {int(bx) * per + int(ls)}')
        calc[('T05', f'No.{n:03d}')] = N if ok else A
