def ledger(path):
    """2026年3月の受払明細（システムからの出力）。月末の残高は帳簿在庫一覧と同じ"""
    rng = random.Random(41)
    days = [d for d in drange(D(2026, 3, 1), D(2026, 3, 31)) if is_bd(d)]
    rows, seq = [], {'入庫': 100, '出庫': 400}
    for it, book in dm.BOOK.items():
        for _ in range(200):
            mv = []
            for d in days:
                for _k in range(rng.choice([2, 3, 3, 4, 5])):
                    mv.append((d, '出庫', rng.randint(1, max(2, book // 60))))
                if rng.random() < 0.3:
                    mv.append((d, '入庫', rng.randint(max(2, book // 12), max(4, book // 5))))
            net = sum(q if k == '入庫' else -q for _, k, q in mv)
            bal, ok = book - net, book - net >= 0
            run = []
            for d, k, q in mv:
                bal += q if k == '入庫' else -q
                ok = ok and bal >= 0
                run.append(bal)
            if ok:
                break
        assert ok and run[-1] == book, it
        rows.append([it, dm.PI[it][1], '', '前月繰越', '', '', '', yen(book - net)])
        for (d, k, q), b in zip(mv, run):
            seq[k] += 1
            rows.append(['', '', md(d), k, f'{"NK" if k == "入庫" else "SJ"}2603-{seq[k]:04d}', yen(q) if k == '入庫' else '', yen(q) if k == '出庫' else '', yen(b)])
        rows.append(['', '', '3/31', '月末残高', '', '', '', yen(book)])
    g = table_print(path, 'Z0310 品番別 受払明細　対象：2026/03/01〜2026/03/31　倉庫：物流センター　出力日時 2026/04/08 09:15　出力者 坂口',
                    [('品番', 30, 'l'), ('品名', 62, 'l'), ('日付', 18, 'c'), ('区分', 24, 'c'), ('伝票番号', 34, 'c'), ('入庫数', 24, 'r'), ('出庫数', 24, 'r'), ('残高', 28, 'r')], rows,
                    foot=f'合計 {len(dm.BOOK)} 品番　{len(rows):,} 行　　※ 月末残高は帳簿在庫一覧（2026/3/31）の帳簿数量と同じ。')
    INFO['pages'] = g.pno + 1
    return g


