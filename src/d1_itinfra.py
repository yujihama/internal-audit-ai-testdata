def mdays(y, m):
    return [d for d in drange(D(y, m, 1), D(y + (m == 12), m % 12 + 1, 1) - dt.timedelta(days=1))]


def gen_log(y, m, rng):
    """1か月分のバックアップ実行ログ。戻り値: (行のリスト, 日ごとの結果)"""
    lines, res = [], {}
    for d in mdays(y, m):
        worst = '○'
        for job, _, _, sch, _, state, _ in JOBS:
            if state != '有効' or (sch.startswith('日曜') and d.weekday() != 6):
                continue
            hh, mm = sch.split(' ')[1].split(':')
            st_ = f'{hh}:{mm}:{rng.randint(1, 9):02d}'
            size = {'BK_APP01': 18, 'BK_DB01': 41, 'BK_ACC01': 12, 'BK_ML01': 26, 'BK_FS01': 310}[job] * rng.uniform(0.97, 1.04)
            dur = int(size * rng.uniform(55, 70)) if job != 'BK_FS01' else int(size * 28)
            en = f'{int(hh) + (int(mm) * 60 + dur) // 3600:02d}:{((int(mm) * 60 + dur) % 3600) // 60:02d}:{dur % 60:02d}'
            if (d, job) in FAIL:
                rc, msg, rt, _, _ = FAIL[(d, job)]
                lines.append(f'{d:%Y-%m-%d} {job:<9} 開始 {st_} 終了 {hh}:{int(mm) + 1:02d}:{rng.randint(10, 50)} 結果=異常終了 RC={rc} サイズ=0.0GB {msg}')
                lines.append(f'{d:%Y-%m-%d} {job:<9} 開始 {rt}:12 終了 {int(rt[:2]) + 1}:{rng.randint(10, 40)}:27 結果=正常終了 RC=0 サイズ={size:.1f}GB 手動再実行')
                worst = '×'
            elif (d, job) in WARN:
                lines.append(f'{d:%Y-%m-%d} {job:<9} 開始 {st_} 終了 {en} 結果=警告終了 RC=4 サイズ={size:.1f}GB 使用中のファイルをスキップ（{rng.randint(2, 4)}件）')
                worst = '△' if worst == '○' else worst
            else:
                lines.append(f'{d:%Y-%m-%d} {job:<9} 開始 {st_} 終了 {en} 結果=正常終了 RC=0 サイズ={size:.1f}GB')
        res[d] = worst
    return lines, res


